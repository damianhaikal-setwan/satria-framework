'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'frontend','satria-next4.js'),'utf8');
const css=fs.readFileSync(path.join(root,'frontend','satria-next4.css'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
const scripts=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)].filter(m=>!m[1].includes('src='));
for(const [i,m] of scripts.entries())assert.doesNotThrow(()=>new vm.Script(m[2],{filename:'index-inline-'+i+'.js'}),'JavaScript inline '+i+' syntax failed');
assert.doesNotThrow(()=>new vm.Script(js),'SATRIA NEXT4 module syntax');
assert.match(html,/\['satria360','SATRIA 360°'\]/,'360 nav missing');
assert.match(html,/satria360:\(\)=>window\.SATRIA_NEXT4\?\.vSatria360/,'360 view not wired');
assert.match(html,/window\.SATRIA_NEXT4\?\.enhance\?\.\(\)/,'Enhancement not wired into render');
assert.match(html,/satria360','analisa','dok','lap'/,'Operator/Viewer role gate missing 360');
assert.match(html,/<link rel="stylesheet" href="\.\/frontend\/satria-next4\.css">/,'Design CSS missing');
assert.match(html,/<script src="\.\/frontend\/satria-next4\.js"><\/script>/,'Modular JS missing');
assert.match(js,/const visible=\(\)=>satriaOpsVisiblePaket\(\)/,'360 must use scoped visibility');
assert.match(js,/const hasScope=.*satriaOpsVisiblePaket\(\)/,'360 header must scope package links');
assert.match(js,/const p=visible\(\)\.find/,'360 detail must not use arbitrary P id');
assert.doesNotMatch(js,/\b(?:supabase|\.rpc\(|\.from\(|\.insert\(|\.update\(|\.delete\(|sync\(|S\.paket\s*=|S\.rupBank\s*=)/,'Presentation module must not mutate cloud/state');
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.match(css,/\.s4-module-head/);
assert.match(sw,/satria-v3\.0\.59\.34/);
assert.match(sw,/satria-next4\.css/);
assert.match(sw,/satria-next4\.js/);
assert.match(manifest.description,/3\.0\.59\.34/);
assert.equal((html.match(/frontend\/satria-next4\.js/g)||[]).length,1);
console.log('PASS — '+scripts.length+' inline scripts parse; scoped 360, design assets, roles, module render, reduced motion, PWA cache, read-only guard');
