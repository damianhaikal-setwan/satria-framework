'use strict';
const assert=require('node:assert/strict');
require('../frontend/refactor/js/00-core-guards.js');
const api=globalThis.SATRIA_CORE_GUARDS;
assert.equal(api.imageSrc('x" onerror="globalThis.pwned=true'),'');
assert.equal(api.imageSrc('javascript:alert(1)'),'');
assert.equal(api.imageSrc('data:image/svg+xml;base64,PHN2Zz4='),'');
assert.equal(api.imageSrc('http://example.org/a.png'),'');
assert.equal(api.imageSrc('https://cdn.example.org/kop.png'),'https://cdn.example.org/kop.png');
assert.equal(api.imageSrc('data:image/png;base64,Zm9v'),'data:image/png;base64,Zm9v');
assert.equal(api.csvCell('=HYPERLINK("https://evil", "open")'),'"\'=HYPERLINK(""https://evil"", ""open"")"');
assert.equal(api.csvCell('  +SUM(1,1)'),'"\'  +SUM(1,1)"');
assert.equal(api.csvCell('Nama kantor'),'"Nama kantor"');
const state={paket:[{id:'p1',nama:'Paket uji',tahun:2026,items:[],penawaran:[]}],rupBank:[],sampah:[]};
const orig=JSON.parse(JSON.stringify(state.paket));
const moved=api.archive(state,'paket','p1','Tester','2026-11-11T10:00:00Z');
assert.equal(state.paket.length,0);
assert.equal(state.sampah.length,1);
assert.deepEqual(moved.record,orig[0]);
const saved=JSON.parse(JSON.stringify(state));
api.restore(saved,moved.id);
assert.deepEqual(saved.paket,orig);
assert.deepEqual(saved.sampah,[]);
assert.deepEqual(state.paket,[],'archive should not accidentally re-add active record');
const duplicate=JSON.parse(JSON.stringify(state));duplicate.paket.push(orig[0]);
assert.throws(()=>api.restore(duplicate,moved.id),/ID sudah digunakan/);
assert.equal(duplicate.sampah.length,1,'Failed recovery must retain trash record');
assert.throws(()=>api.archive(state,'evil','id','Tester'),/tidak didukung/);
console.log('PASS core guards: malicious image blocked, CSV neutralized, archive/restore collision safe');
