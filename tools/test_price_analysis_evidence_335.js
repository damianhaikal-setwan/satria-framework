'use strict';
const assert=require('node:assert/strict');
const {analyze,specConflict}=require('../frontend/satria-price-analysis.js');
const basic=(id,nama,spec)=>({id,nama,spesifikasi:spec,satuan:'Kotak',vol:5,hs:5000});
const items=[basic('staple','Isi Staples No. 10','Isi Staples No. 10'),basic('pulpen','Pulpen Faster','Pulpen Faster')];
const offer=(id,pen,stapleName,ballName)=>({id,pen,harga:{staple:5000,pulpen:4000},nego:{staple:4900,pulpen:3900},ongkir:0,sumberHarga:'Katalog Elektronik',tanggalHarga:'2026-06-02',catalogRefs:{staple:{name:stapleName,unit:'Kotak',seller:pen,date:'2026-06-02',displayPrice:5000,link:'https://katalog.inaproc.id/a/this-is-a-very-long-slug-with-many-characters-so-it-will-wrap'},pulpen:{name:ballName,unit:'Kotak',seller:pen,date:'2026-06-02',displayPrice:4000,link:'https://katalog.inaproc.id/b'}}});
const p={id:'r',rup:'67122699',nama:'ATK',tahun:2026,opd:'o',pagu:100000,items,penawaran:[offer('a','PRIMA','Isi Staples No. 10','Pulpen Faster'),offer('b','RIAN','Isi Staples No. 24/6','Pulpen Pilot')]};
const before=JSON.stringify(p);
const a=analyze(p,{suppliers:{PRIMA:'PRIMA',RIAN:'RIAN'},validWinnerId:'a'});
assert.equal(a.referenceCount,4,'all references retain metadata completeness count');
assert.equal(a.comparativeItems,0,'obvious model conflicts do not contribute to comparison statistics');
assert.equal(a.items[0].average,null);
assert.equal(a.items[1].average,null);
assert.equal(a.offers[1].detail[0].specWarnings.length,1);
assert.equal(a.offers[1].detail[1].specWarnings.length,1);
assert(a.issues.some(x=>x.code==='SPEC_HINT_b'));
assert.equal(JSON.stringify(p),before,'read-only analysis must not change source data');
assert(specConflict({nama:'Isi Staples No. 10'}, {name:'Isi Staples No. 24/6'}).length);
assert.deepEqual(specConflict({nama:'HVS A4 70 GR'}, {name:'Kertas HVS A4 70gsm'}),[]);
console.log('PASS v3.0.59.35 evidence: no10-vs-24/6, Faster-vs-Pilot, stats screening, read-only');
