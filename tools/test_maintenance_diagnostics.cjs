'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const code=fs.readFileSync(path.join(__dirname,'../frontend/refactor/maintenance/diagnostics.js'),'utf8');
const listeners={};const elements={script:[],style:[]};
const window={addEventListener:(kind,fn)=>{listeners[kind]=fn}};
const context={window,document:{addEventListener:()=>{},querySelectorAll(sel){return sel.includes('script')?elements.script:elements.style}},location:{href:'https://example.test/'},URL,Blob,Date,setTimeout};
vm.runInNewContext(code,context,{timeout:1000});
assert.equal(typeof window.SATRIA_MAINTENANCE.inspect,'function');
assert.equal(window.SATRIA_MAINTENANCE.inspect().status,'tidak ada error terdeteksi');
listeners.error({target: {tagName:'SCRIPT', src:'https://example.test/secret.js?token=sensitive&foo=bar'}});
let report=window.SATRIA_MAINTENANCE.inspect();
assert.equal(report.errorCount,1);
assert.equal(report.errors[0].detail,'secret.js');
assert(!JSON.stringify(report).includes('sensitive'));
listeners.unhandledrejection({reason:new TypeError('do not disclose details')});
report=window.SATRIA_MAINTENANCE.inspect();
assert.equal(report.errorCount,2);
assert.equal(report.errors[1].detail,'TypeError');
assert(Object.isFrozen(window.SATRIA_MAINTENANCE));
console.log('PASS diagnostics: isolated, no sensitive URLs, records bootstrap JS/assets/rejection');
